-- 受領物: 検証環境で運用チームが適用しているログオン処理
CREATE OR REPLACE TRIGGER TRG_APP_LOGON
AFTER LOGON ON DATABASE
BEGIN
  IF SYS_CONTEXT('USERENV', 'SESSION_USER') = 'SHIPAPP' THEN
    EXECUTE IMMEDIATE 'ALTER SESSION SET NLS_SORT = JAPANESE_M';
    EXECUTE IMMEDIATE 'ALTER SESSION SET NLS_COMP = LINGUISTIC';
    EXECUTE IMMEDIATE 'ALTER SESSION SET NLS_DATE_FORMAT = ''YYYY-MM-DD HH24:MI:SS''';
  END IF;
END;
/
